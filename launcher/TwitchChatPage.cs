using System.Globalization;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.Web.WebView2.Core;

namespace D2Checkpoint.Launcher;

internal static partial class TwitchChatPage
{
    internal enum Phase { Prepare, Ready, Confirm }

    internal static string ChannelUrl(string login) => $"https://www.twitch.tv/popout/{login}/chat";

    internal static bool IsChannel(string? text, string login) =>
        Uri.TryCreate(text, UriKind.Absolute, out var uri) && uri.Scheme == Uri.UriSchemeHttps && uri.IsDefaultPort &&
        uri.UserInfo.Length == 0 && uri.Host.Equals("www.twitch.tv", StringComparison.OrdinalIgnoreCase) &&
        uri.AbsolutePath.Equals($"/popout/{login}/chat", StringComparison.OrdinalIgnoreCase) && uri.Fragment.Length == 0 &&
        uri.Query is "" or "?popout" or "?popout=";

    internal static bool IsRequestId(string? requestId) => requestId is { Length: >= 1 and <= 80 } &&
        requestId.All(ch => char.IsAsciiLetterOrDigit(ch) || ch is '-' or '_');

    internal static bool IsQueueCommand(string? command) => command is { Length: >= 1 and <= 140 } &&
        command == command.Trim() && QueueCommandPattern().IsMatch(command);

    [GeneratedRegex(@"\A!queue [a-z0-9][a-z0-9-]{0,15}(?: [a-z0-9][a-z0-9-]{0,15}){0,2} [^#\p{Cc}\p{Cf}\p{Zl}\p{Zp}]+#[0-9]{4}\z", RegexOptions.CultureInvariant)]
    private static partial Regex QueueCommandPattern();

    internal static string ProbeScript(string login, string command, long deadline, Phase phase) =>
        $"({InspectCommand})({JsonSerializer.Serialize(login)}, {JsonSerializer.Serialize(command)}, {deadline.ToString(CultureInfo.InvariantCulture)}, {(int)phase})";

    internal static Task InsertTextAsync(CoreWebView2 core, string command, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        return core.CallDevToolsProtocolMethodAsync("Input.insertText", JsonSerializer.Serialize(new { text = command })).WaitAsync(cancellationToken);
    }

    internal static Task DispatchEnterAsync(CoreWebView2 core, bool down, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var payload = JsonSerializer.Serialize(new
        {
            // Chromium's native button activation uses the Enter keypress generated by keyDown with text.
            type = down ? "keyDown" : "keyUp", key = "Enter", code = "Enter", text = down ? "\r" : "",
            windowsVirtualKeyCode = 13, nativeVirtualKeyCode = 13
        });
        return core.CallDevToolsProtocolMethodAsync("Input.dispatchKeyEvent", payload).WaitAsync(cancellationToken);
    }

    private const string InspectCommand = """
        (login, command, deadline, phase) => {
          const isTarget = () => location.origin === 'https://www.twitch.tv' &&
            location.pathname.toLowerCase() === `/popout/${login}/chat` &&
            ['', '?popout', '?popout='].includes(location.search) && location.hash === '';
          const visible = node => {
            if (!node?.getClientRects().length) return false;
            const bounds = node.getBoundingClientRect();
            if (bounds.width < 2 || bounds.height < 2 || bounds.bottom <= 0 || bounds.right <= 0 ||
                bounds.top >= innerHeight || bounds.left >= innerWidth) return false;
            const style = getComputedStyle(node);
            return style.visibility === 'visible' && style.opacity !== '0';
          };
          const blocked = () => Array.from(document.querySelectorAll(
            '[role="dialog"], [aria-modal="true"], input[type="password"], input[autocomplete="one-time-code"], ' +
            '[data-a-target="login-button"], [data-a-target="chat-login-button"]'
          )).some(visible);
          if (!isTarget() || document.hidden || Date.now() >= deadline) return 'left';
          if (blocked()) return 'blocked';
          const editors = Array.from(document.querySelectorAll(
            'textarea[data-a-target="chat-input"], [data-a-target="chat-input"] textarea, ' +
            '[data-a-target="chat-input"][contenteditable="true"], [data-a-target="chat-input"] [contenteditable="true"]'
          )).filter(visible);
          if (editors.length === 0) return 'waiting';
          if (editors.length !== 1) return 'unavailable';
          const [editor] = editors;
          const isTextArea = editor.tagName === 'TEXTAREA';
          const text = () => {
            if (isTextArea) return editor.value;
            const draft = editor.cloneNode(true);
            for (const placeholder of draft.querySelectorAll('[data-slate-placeholder]')) placeholder.remove();
            for (const sentinel of draft.querySelectorAll('[data-slate-zero-width]')) {
              sentinel.textContent = sentinel.textContent.replace(/\uFEFF/g, '');
            }
            return draft.textContent;
          };
          const hasEmote = () => editor.querySelector('img, [data-slate-void], [data-emote-name]');
          if (phase === 2) return !text() && !hasEmote() ? 'cleared' : 'waiting';
          if (editor.disabled || editor.readOnly || editor.getAttribute('aria-disabled') === 'true') return 'unavailable';
          const buttons = Array.from(document.querySelectorAll('button[data-a-target="chat-send-button"]')).filter(visible);
          if (buttons.length === 0) return 'waiting';
          if (buttons.length !== 1) return 'unavailable';
          const [button] = buttons;

          const validFocus = node => document.hasFocus() && document.activeElement === node &&
            isTarget() && !document.hidden && !blocked() && Date.now() < deadline;
          if (phase === 0) {
            if (text() || hasEmote()) return 'draft';
            editor.focus({ preventScroll: true });
            if (!validFocus(editor)) return 'unavailable';
            if (text() || hasEmote()) return 'draft';
            if (!isTextArea) {
              const selection = document.getSelection();
              const leaf = editor.querySelector('[data-slate-zero-width]')?.firstChild;
              if (selection && leaf?.nodeType === Node.TEXT_NODE) selection.collapse(leaf, leaf.length);
              if (!selection?.isCollapsed || !editor.contains(selection.anchorNode)) return 'unavailable';
            }
            return 'editor-focused';
          }

          if (hasEmote()) return 'draft-changed';
          const current = text();
          if (current && current !== command) return 'draft-changed';
          const composerAccepted = () => {
            if (text() !== command || hasEmote()) return false;
            if (isTextArea) return true;
            const slate = Array.from(editor.querySelectorAll('[data-slate-string]'));
            return slate.map(node => node.textContent).join('') === command && !editor.querySelector('[data-slate-placeholder]');
          };
          if (!composerAccepted() || !button.isConnected || button.disabled || button.getAttribute('aria-disabled') === 'true') return 'waiting';
          if (!validFocus(editor)) return 'unavailable';
          const bounds = button.getBoundingClientRect();
          if (!button.contains(document.elementFromPoint((bounds.left + bounds.right) / 2, (bounds.top + bounds.bottom) / 2))) return 'unavailable';
          button.focus({ preventScroll: true });
          if (!validFocus(button) || !composerAccepted() || button.disabled || button.getAttribute('aria-disabled') === 'true') return 'unavailable';
          return 'send-focused';
        }
        """;
}
